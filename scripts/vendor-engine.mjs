// Rebuilds site/vendor/tyrhq-engine.js from Tyr HQ's source (https://github.com/wackoisgod/tyrhq, MIT):
// the talent tree rules, stat calculation and firepower from src/lib/game-engine, bundled into one
// readable ES module with the same function names as upstream.
//
//   git clone https://github.com/wackoisgod/tyrhq /tmp/tyrhq
//   npm install && node scripts/vendor-engine.mjs /tmp/tyrhq
//   npm test
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const upstream = path.resolve(process.argv[2] ?? '');
const lib = path.join(upstream, 'src', 'lib');
if (!process.argv[2] || !fs.existsSync(path.join(lib, 'game-engine', 'build.ts'))) {
  console.error('usage: node scripts/vendor-engine.mjs <path to a wackoisgod/tyrhq checkout>');
  process.exit(1);
}
const commit = execFileSync('git', ['-C', upstream, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
const out = path.resolve(import.meta.dirname, '..', 'site', 'vendor', 'tyrhq-engine.js');

const entry = `
export {
  MAX_TOTAL_TALENT_POINTS,
  canIncrementTalentPoint,
  computeBuild,
  computeBuildFirepower,
  createPlannerCatalog,
  getDefaultSelection,
  getDeltaTone,
  getPlannerTalentsForVehicle,
  getPointsSpentInTiersBelow,
  getTalentTierUnlockRequirement,
  groupStatCards,
  talentPrerequisitesSatisfied,
} from '$lib/game-engine/build';
export { fillTalentDescription } from '$lib/game-engine/component-format';
`;

await build({
  stdin: { contents: entry, resolveDir: lib, loader: 'ts' },
  bundle: true,
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  alias: { $lib: lib },
  tsconfigRaw: {},
  absWorkingDir: upstream, // keeps the per-file comments as src/lib/... paths
  outfile: out,
  banner: {
    js: [
      `// Generated by scripts/vendor-engine.mjs from wackoisgod/tyrhq@${commit} (src/lib/game-engine). Do not edit.`,
      '// Tyr HQ, MIT License, Copyright (c) 2026 Tyr HQ contributors: https://github.com/wackoisgod/tyrhq/blob/main/LICENSE',
    ].join('\n'),
  },
  logLevel: 'warning',
});
console.log(`site/vendor/tyrhq-engine.js from tyrhq@${commit} (${(fs.statSync(out).size / 1024).toFixed(0)} KiB)`);
